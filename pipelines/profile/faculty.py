# จับคำยาวก่อนเสมอ + ใช้ word boundary สำหรับคำภาษาอังกฤษ
_PAIRS = sorted(((a, f) for f, xs in ALIASES.items() for a in xs), key=lambda x: -len(x[0]))
_PATTERNS = [rf"\b{re.escape(a)}\b" if a.isascii() else re.escape(a) for a, _ in _PAIRS]
_RE = re.compile("|".join(_PATTERNS), re.IGNORECASE)
_TO = {a.lower(): f for a, f in _PAIRS}

SELF_CUES = ("ผมเรียน", "ฉันเรียน", "เราเรียน", "หนูเรียน", "เค้าเรียน", "เรียนอยู่", "อยู่คณะ", "ผมอยู่", "ฉันอยู่",
             "ตัวเองเรียน", "เราอยู่", "ผมเด็ก", "ฉันเด็ก", "เราเด็ก", "ผมเป็น", "ฉันเป็น", "เราเป็น")
PARTNER_CUES = ("อยากได้", "ชอบผู้", "ชอบคน", "สเปก", "สเป็ค", "แฟน", "ผู้หญิง", "ผู้ชาย", "คนที่", "หาคน", "ขอคน",
                "เจอคน", "คนเรียน", "เรียนคณะ", "เด็กคณะ", "สาย")
NON_FACULTY_PHRASES = ("ไปหาหมอ", "พบหมอ", "นัดหมอ", "หาหมอ", "ตรวจหมอ", "หาคุณหมอ", "หมอมา")


def _char_bigrams(text: str) -> set:
    t = re.sub(r"\s+", "", text.lower())
    return {t[i:i + 2] for i in range(max(1, len(t) - 1))}


def fuzzy_match(text: str, min_similarity: float = 0.70) -> str:
    """Fuzzy matching ด้วย Character Bigram Jaccard รองรับคำสะกดเพี้ยน/พิมพ์ผิด"""
    if not text:
        return None
    q_bigrams = _char_bigrams(text)
    if not q_bigrams:
        return None
    best_fac, best_sim = None, 0.0
    for alias, fac in _PAIRS:
        if len(alias) < 3 or alias.isascii():
            continue
        a_bigrams = _char_bigrams(alias)
        sim = len(q_bigrams & a_bigrams) / max(1, len(q_bigrams | a_bigrams))
        if sim > best_sim:
            best_sim, best_fac = sim, fac
    return best_fac if best_sim >= min_similarity else None


def normalize(text: str):
    """ชื่อคณะที่ผู้ใช้พิมพ์ -> ชื่อเต็ม (รองรับชื่อย่อและพิมพ์ผิด)"""
    if not text:
        return None
    m = _RE.search(text)
    if m:
        return _TO.get(m.group(0).lower())
    return fuzzy_match(text)


def parse(msg: str) -> dict:
    """สกัดคณะและวิเคราะห์บริบทขอบเขต (ตัวเอง vs คู่) โดยไม่จำกัดกรอบ 20 ตัวอักษร"""
    out = {"self": None, "wants": [], "spans": []}
    if not msg:
        return out

    for m in _RE.finditer(msg):
        word = m.group(0).lower()
        fac = _TO.get(word)
        if not fac:
            continue
        
        # ป้องกันคำกำกวม เช่น "ไปหาหมอมา"
        if word in ("หมอ", "แพทย์") and any(nf in msg for nf in NON_FACULTY_PHRASES):
            continue

        start_idx = m.start()
        
        # ตรวจสอบว่ามีคำว่า "คณะ" นำหน้าก่อนหน้า match หรือไม่ เพื่อเก็บเข้า span ป้องกัน LLM สับสน
        pre_span = msg[max(0, start_idx - 10):start_idx]
        span_word = m.group(0)
        for prefix in ("เรียนคณะ", "เด็กคณะ", "อยู่คณะ", "คณะ", "สาย"):
            if pre_span.endswith(prefix):
                span_word = prefix + span_word
                break

        # ตรวจสอบบริบทก่อนหน้าทั้งหมดตั้งแต่ต้นประโยค
        before = msg[:start_idx]
        last_self = max((before.rfind(c) for c in SELF_CUES), default=-1)
        last_partner = max((before.rfind(c) for c in PARTNER_CUES), default=-1)

        # สเปกคู่มีผลเหนือกว่าถ้าพบคำบ่งชี้ของคู่ หรืออยู่ภายใต้คำบอกชอบ
        if last_partner > last_self:
            if fac not in out["wants"]:
                out["wants"].append(fac)
        elif last_self >= 0 and last_self > last_partner:
            if not out["self"]:
                out["self"] = fac
        else:
            # ถ้าไม่มี cue นำหน้า ตรวจบริบทด้านหลังถัดไป (เช่น "หมอคนไหน", "วิศวะที่น่ารัก")
            after = msg[m.end():m.end() + 30]
            after_partner = any(c in after for c in PARTNER_CUES)
            if after_partner:
                if fac not in out["wants"]:
                    out["wants"].append(fac)
            elif before.strip().endswith("เรียน") or msg.strip().startswith("เรียน"):
                if not out["self"]:
                    out["self"] = fac
            else:
                # ไม่มีบริบทบ่งชี้ว่าพูดถึงคณะในแง่หาคู่/ตัวเอง -> ข้าม
                continue

        if span_word not in out["spans"]:
            out["spans"].append(span_word)
        if m.group(0) not in out["spans"]:
            out["spans"].append(m.group(0))

    return out
