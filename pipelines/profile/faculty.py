"""คณะ: แปลงชื่อย่อ/ชื่อเล่นเป็นชื่อเต็ม + แยกว่าพูดถึงคณะตัวเอง หรือคณะที่อยากได้ในคู่ (ใช้กฎ ไม่ใช้ LLM)

  normalize("วิศวะ")                        -> "วิศวกรรมศาสตร์"
  parse("ชอบผู้หญิงเรียน วิศวะ")             -> {"self": None, "wants": ["วิศวกรรมศาสตร์"], "spans": ["วิศวะ"]}
  parse("ผมเรียนหมอ อยากได้แฟนสายนิติ")      -> {"self": "แพทยศาสตร์", "wants": ["นิติศาสตร์"], ...}
"""
import re

ALIASES = {
    "วิศวกรรมศาสตร์": ["วิศวกรรมศาสตร์", "วิศวกรรม", "วิศวะ", "วิศว", "engineer"],
    "แพทยศาสตร์": ["แพทยศาสตร์", "หมอ", "แพทย์"],
    "ทันตแพทยศาสตร์": ["ทันตแพทยศาสตร์", "ทันตแพทย์", "ทันตะ", "หมอฟัน"],
    "เภสัชศาสตร์": ["เภสัชศาสตร์", "เภสัช"],
    "พยาบาลศาสตร์": ["พยาบาลศาสตร์", "พยาบาล"],
    "การแพทย์แผนไทย": ["การแพทย์แผนไทย", "แพทย์แผนไทย", "แผนไทย"],
    "วิทยาศาสตร์": ["วิทยาศาสตร์", "วิทย์"],
    "วิทยาการจัดการ": ["วิทยาการจัดการ", "วจก", "บริหารธุรกิจ", "บริหาร"],
    "นิติศาสตร์": ["นิติศาสตร์", "นิติ", "กฎหมาย"],
    "เศรษฐศาสตร์": ["เศรษฐศาสตร์", "เศรษฐ", "เศรษฐ์"],
    "ศิลปศาสตร์": ["ศิลปศาสตร์", "ศิลปศาสตร์", "ศิลป์ศาสตร์", "อักษร"],
    "สถาปัตยกรรมศาสตร์": ["สถาปัตยกรรมศาสตร์", "สถาปัตย์", "สถาปัต", "ถาปัด"],
    "เทคนิคการแพทย์": ["เทคนิคการแพทย์", "เทคนิคการแพทย์", "เทคนิคแพทย์"],
    "อุตสาหกรรมเกษตร": ["อุตสาหกรรมเกษตร", "อุตสา"],
    "ทรัพยากรธรรมชาติ": ["ทรัพยากรธรรมชาติ", "ทรัพยากร", "เกษตร"],
    "การจัดการสิ่งแวดล้อม": ["การจัดการสิ่งแวดล้อม", "สิ่งแวดล้อม"],
}
# จับคำยาวก่อน: "แพทย์แผนไทย" ต้องไม่ถูกจับเป็น "แพทย์", "ทันตแพทย์" ต้องไม่เป็น "แพทย์"
_PAIRS = sorted(((a, f) for f, xs in ALIASES.items() for a in xs), key=lambda x: -len(x[0]))
# ไม่ใส่คำสั้นที่ซ้อนในคำทั่วไป เช่น "วิทยา" (มหาวิทยาลัย) "พยา" (พยายาม) "เทคนิค"
_RE = re.compile("|".join(re.escape(a) for a, _ in _PAIRS))
_TO = dict(_PAIRS)

SELF_CUES = ("ผมเรียน", "ฉันเรียน", "เราเรียน", "หนูเรียน", "เค้าเรียน", "เรียนอยู่", "อยู่คณะ", "ผมอยู่", "ฉันอยู่")
PARTNER_CUES = ("อยากได้", "ชอบผู้", "ชอบคน", "สเปก", "สเป็ค", "แฟน", "ผู้หญิง", "ผู้ชาย", "คนที่", "หาคน", "ขอคน", "เจอคน")
WINDOW = 20      # ดูคำนำหน้าชื่อคณะย้อนหลังกี่ตัวอักษร


def normalize(text: str):
    """ชื่อคณะที่ผู้ใช้พิมพ์ -> ชื่อเต็ม (ไม่รู้จัก = None)"""
    m = _RE.search(text or "")
    return _TO[m.group(0)] if m else None


def parse(msg: str) -> dict:
    out = {"self": None, "wants": [], "spans": []}
    for m in _RE.finditer(msg or ""):
        before = msg[max(0, m.start() - WINDOW):m.start()]
        fac = _TO[m.group(0)]
        # คำที่อยู่ใกล้ชื่อคณะที่สุดเป็นตัวตัดสิน ("ผมเรียนวิศวะ อยากได้แฟนหมอ" -> self=วิศวะ, wants=หมอ)
        last_self = max((before.rfind(c) for c in SELF_CUES), default=-1)
        last_partner = max((before.rfind(c) for c in PARTNER_CUES), default=-1)
        if last_partner > last_self:
            if fac not in out["wants"]:
                out["wants"].append(fac)
        elif last_self >= 0 and not out["self"]:
            out["self"] = fac
        else:
            continue
        out["spans"].append(m.group(0))
    return out
