MAX_VARIANTS = 5


def partner_term(query: str):
    """คำเรียกอีกฝ่ายตัวแรกในคำถาม — "เพื่อน" ใช้เมื่อไม่มีคำอื่น ("นัดเพื่อนกับแฟน" ต้องไม่เปลี่ยนเพื่อนเป็นแฟน)"""
    found = [t for t in _ORDER if t in query]
    if not found:
        return None
    others = [t for t in found if t != "เพื่อน"]
    return others[0] if others else found[0]


def _slang_variants(query: str) -> list:
    import re
    q_norm = re.sub(r"\s+", " ", query.strip())
    q_lower = q_norm.lower()
    # 1. Match multi-word / English phrases directly (e.g. "red flag", "yellow flag", "นัดครั้งแรก")
    for phrase, alts in COLLOQUIAL.items():
        if " " in phrase or any(c.isascii() and c.isalpha() for c in phrase):
            if phrase in q_lower:
                pattern = re.compile(re.escape(phrase), re.IGNORECASE)
                return [pattern.sub(alt, q_norm) for alt in alts]
    # 2. Token-based matching for Thai compound words
    from pythainlp.tokenize import word_tokenize
    tokens = word_tokenize(q_norm, engine="newmm", keep_whitespace=True)
    for i in range(len(tokens)):
        for n in (2, 1):                         # "ขอไลน์" ถูกตัดเป็น "ขอ"+"ไลน์" -> ดูคู่คำติดกันก่อน
            phrase = "".join(tokens[i:i + n])
            if len(tokens[i:i + n]) == n and phrase in COLLOQUIAL:
                return ["".join(tokens[:i] + [alt] + tokens[i + n:]) for alt in COLLOQUIAL[phrase]]
    return []


def variants(query: str, extra=()) -> list:
    """[คำถามเดิม, แบบใช้คำกลางแทนคำเรียกอีกฝ่าย..., แบบแปลงภาษาพูด...] (ไม่ซ้ำ ไม่เกิน MAX_VARIANTS) + หัวข้อจาก LLM (extra)"""
    out = [query]
    term = partner_term(query)
    if term:
        out += [query.replace(term, c) for c in CANON if c != term]
    out += _slang_variants(query)
    return list(dict.fromkeys(list(dict.fromkeys(out))[:MAX_VARIANTS] + list(extra)))


def hint(query: str, extra=()) -> str:
    """คำถามที่ส่งให้ LLM: แนบคำที่เอกสารอาจใช้แทน (วัดจริง: ไม่แนบ -> "ควรเริ่มทักยังไงดี" ตอบว่าไม่มีข้อมูล ทั้งที่ context มีคำตอบ)
    ด่านหลัง (verify_answer) ยังเทียบกับคำถามเดิม"""
    alts = variants(query)[1:]
    out = query + (f"\n(คำในเอกสารอาจใช้คำอื่นที่หมายถึงเรื่องเดียวกัน เช่น: {' / '.join(alts)})" if alts else "")
    return out + (f"\n(ประเด็นในเอกสารที่เกี่ยวข้อง: {' / '.join(extra)})" if extra else "")


def normalize(text: str) -> str:
    """ใช้ตอนเทียบประโยคคำตอบกับแหล่ง (ด่านหลัง LLM): ทำคำเรียกอีกฝ่ายให้เป็นคำเดียวกันทั้งสองฝั่ง (ไม่รวม "เพื่อน")"""
    for t in _ORDER:
        if t != "เพื่อน":
            text = text.replace(t, "อีกฝ่าย")
    return text
